"""Regenerate docs/assets/layout.js (the website's live demo) from the real floor plan fixture.

Run from the repository root:  python docs/source/build_demo_layout.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FIXTURE = ROOT / "floorplan" / "fixtures" / "floorplan_layout.json"
OUTPUT = ROOT / "docs" / "assets" / "layout.js"

# Same rules as floorplan.views._desk_payload: these departments are not bookable seats.
NON_SEAT_DEPARTMENTS = {"Utility/Resource", "Walkway"}


def is_kiosk(desk: dict) -> bool:
    return any("kiosk" in (desk[key] or "").casefold() for key in ("identifier", "label", "notes"))


def build() -> dict:
    records = json.loads(FIXTURE.read_text())
    departments = {r["pk"]: r["fields"] for r in records if r["model"] == "floorplan.department"}
    desks = []
    for record in records:
        if record["model"] != "floorplan.desk":
            continue
        desk = record["fields"]
        department = departments[desk["department"]]
        fill = desk["fill_color"] or department["color"]
        seat = is_kiosk(desk) or (department["name"] not in NON_SEAT_DEPARTMENTS and fill.lower() != "#000000")
        desks.append(
            {
                "id": desk["identifier"],
                "row": desk["row_index"],
                "col": desk["column_index"],
                "label": desk["label"],
                "department": department["name"],
                "fill": fill if seat else None,
                "seat": seat,
            }
        )
    desks.sort(key=lambda d: (d["row"], d["col"]))
    used = {d["department"] for d in desks if d["seat"]}
    legend = [
        {"name": d["name"], "color": d["color"]}
        for d in sorted(departments.values(), key=lambda d: d["name"])
        if d["name"] in used
    ]
    return {
        "rows": max(d["row"] for d in desks),
        "cols": max(d["col"] for d in desks),
        "departments": legend,
        "desks": desks,
    }


if __name__ == "__main__":
    payload = json.dumps(build(), separators=(",", ":"))
    OUTPUT.write_text(
        "// Generated by docs/source/build_demo_layout.py from floorplan/fixtures/floorplan_layout.json.\n"
        f"window.WINDOW_WORKS_LAYOUT = {payload};\n"
    )
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")
